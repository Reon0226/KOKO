// 最初に出しておく候補（よく使うひと言）
export const DEFAULTS = ['ありがとう', 'おはよう', 'おやすみ', 'またね', '気持ち', '大丈夫', 'お疲れさま', '嬉しい'];

const kata2hira = s => s.replace(/[ァ-ヶ]/g, c => String.fromCharCode(c.charCodeAt(0) - 0x60));
const uniq = arr => [...new Set(arr)];

// 手入力の検索（読み or 文字）
export function searchGuides(query, max = 12) {
  const q = kata2hira(String(query || '').trim());
  if (!q) return DEFAULTS.slice();
  const starts = DICT.filter(([r, w]) => r.startsWith(q) || w.startsWith(q)).map(([, w]) => w);
  const incl = DICT.filter(([r, w]) => r.includes(q) || w.includes(q)).map(([, w]) => w);
  return uniq([...starts, ...incl]).slice(0, max);
}

// 読み取り補助の結果（直前に書いた数マスの文字列）から、続き・変換のお手本を探す。
// recent: 例 'きもち'。返り値: [{word, span}] span は recent の末尾何文字に対応するか。
export function suggestFromRecognized(recent, max = 8) {
  const text = kata2hira(String(recent || ''));
  const out = [];
  const seen = new Set();
  const chars = Array.from(text);
  for (let n = Math.min(chars.length, 10); n >= 1; n--) {
    const tail = chars.slice(chars.length - n).join('');
    for (const [r, w] of DICT) {
      if (seen.has(w)) continue;
      if (r === tail || (n >= 2 && r.startsWith(tail))) { out.push({ word: w, span: r === tail ? n : 0, reading: r }); seen.add(w); }
    }
    if (out.length >= max) break;
  }
  return out.slice(0, max);
}
